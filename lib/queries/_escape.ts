/**
 * Екранує користувацький рядок перед інтерполяцією в PostgREST-фільтр.
 *
 * PostgREST `.or()` / `.ilike()` парсять кому як роздільник умов, дужки як
 * групування, а `*` у `ilike`-патерні діє як `%`. Якщо вставити сирий пошук
 * (напр. прізвище з комою або дефісом) — фільтр ламається (400) або повертає
 * сміття. Прибираємо ці метасимволи; решта тексту безпечна, бо значення
 * параметризуються драйвером.
 */
export function sanitizePostgrestSearch(input: string): string {
  return input
    .trim()
    .replace(/[,()*\\]/g, ' ')  // метасимволи синтаксису .or()/ilike → пробіл
    .replace(/[%_]/g, ' ')      // LIKE-wildcard-и, щоб користувач не керував патерном
    .replace(/\s+/g, ' ')
    .trim()
}
